    def _clean_free_items(self, items: list[str], *, limit: int) -> list[str]:
        cleaned: list[str] = []
        for item in items:
            text = " ".join(str(item).split())
            if not text:
                continue
            lowered = text.lower()
            if lowered == "key point" or text.startswith("关键要点"):
                continue
            if len(text) > 52:
                text = text[:52]
            if text not in cleaned:
                cleaned.append(text)
            if len(cleaned) >= limit:
                break
        return cleaned

