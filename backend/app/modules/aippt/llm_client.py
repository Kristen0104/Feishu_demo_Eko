    def _normalize_content_outline(self, content: str, *, source_text: str, page_count: int) -> str:
        cleaned = content.strip()
        if cleaned.startswith("```"):
            cleaned = re.sub(r"^```(?:markdown|md)?", "", cleaned, flags=re.I).strip()
            cleaned = re.sub(r"```$", "", cleaned).strip()
        if "# 详细版内容大纲" not in cleaned:
            cleaned = self._fallback_content_outline(source_text=source_text, page_count=page_count)
        return cleaned[:12000]

    def _fallback_content_outline(self, *, source_text: str, page_count: int) -> str:
        topic = source_text.strip().splitlines()[0][:80] or "AI PPT"
        lines = [
            "# 详细版内容大纲",
            "",
            "## Deck narrative",
            f"- 围绕“{topic}”建立背景、问题、方案、执行和收益的完整叙事，保证每页都有可直接放入 PPT 的正文。",
            "",
            "## Slide-by-slide outline",
        ]
        for index in range(1, page_count + 1):
            title = topic if index == 1 else f"{topic} - 第 {index} 个关键议题"
            lines.extend(
                [
                    f"### 第 {index} 页：{title}",
                    f"- 页面目标：说明“{title}”在整体方案中的判断价值和推进意义。",
                    "- 主体内容：",
                    f"  - 当前主题需要先说明业务背景、用户需求和组织目标，避免只呈现抽象标题。",
                    f"  - 本页应补充关键事实、执行动作和可验证指标，让读者离开讲解也能理解结论。",
                    f"  - 内容需要连接前后页面，形成从问题识别到方案落地的连续叙事。",
                    f"  - 每个要点都应能转化为 PPT 页面中的完整业务句子。",
                    "- 视觉建议：使用结构化卡片、流程、对比或指标布局呈现。",
                    "- 右侧标签：背景判断 / 执行动作 / 验收指标",
                    "",
                ]
            )
        return "\n".join(lines).strip()

